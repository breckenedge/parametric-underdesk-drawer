#!/bin/sh
# Writes version.scad (not committed) with the current commit's short hash, for underdesk_drawer.scad's
# debug_stamp. A "+" is added if tracked files have uncommitted changes at the time this runs.
# The hooks in tools/githooks run it on every commit, checkout, merge and rebase; enable them once with
#   git config core.hooksPath tools/githooks
cd "$(git rev-parse --show-toplevel)" || exit 0
sha=$(git rev-parse --short HEAD 2>/dev/null) || sha=nogit
git diff --quiet HEAD 2>/dev/null || sha="$sha+"
printf '// generated by tools/write_version.sh - do not edit or commit\ngit_sha = "%s";\n' "$sha" > version.scad
